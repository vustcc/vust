#!/usr/bin/env node

import { cp, mkdir, readdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(__dirname, '..')
const sourceRoot = path.join(repoRoot, 'target', 'ts-rs-bindings', 'vust-contracts')
const outputRoot = path.join(repoRoot, 'frontend', 'src', 'api', 'generated')
const legacyOutputFile = path.join(outputRoot, 'contracts.ts')

async function main() {
  const modules = await listModules(sourceRoot)

  await rm(legacyOutputFile, { force: true })
  await rm(outputRoot, { recursive: true, force: true })
  await mkdir(outputRoot, { recursive: true })

  for (const moduleName of modules) {
    const sourceDir = path.join(sourceRoot, moduleName)
    const outputDir = path.join(outputRoot, moduleName)
    await cp(sourceDir, outputDir, { recursive: true })
    await writeModuleIndex(outputDir)
  }

  await writeRootIndex(modules)
}

async function listModules(root) {
  const entries = await readdir(root, { withFileTypes: true }).catch((error) => {
    throw new Error(`TypeScript binding source directory is missing: ${root}\n${error.message}`)
  })

  return entries
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort((left, right) => left.localeCompare(right))
}

async function writeModuleIndex(moduleDir) {
  const entries = await readdir(moduleDir, { withFileTypes: true })
  const files = entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.ts') && entry.name !== 'index.ts')
    .map((entry) => path.basename(entry.name, '.ts'))
    .sort((left, right) => left.localeCompare(right))

  const lines = [
    '// This file is auto-generated by scripts/organize-bindings.mjs.',
    '// Do not edit manually.',
    '',
    ...files.map((file) => `export * from './${file}'`),
    '',
  ]
  await writeFile(path.join(moduleDir, 'index.ts'), lines.join('\n'), 'utf8')
}

async function writeRootIndex(modules) {
  const lines = [
    '// This file is auto-generated by scripts/organize-bindings.mjs.',
    '// Do not edit manually.',
    '',
    ...modules.map((moduleName) => `export * from './${moduleName}'`),
    '',
  ]
  await writeFile(path.join(outputRoot, 'index.ts'), lines.join('\n'), 'utf8')
}

main().catch((error) => {
  console.error(error)
  process.exitCode = 1
})
